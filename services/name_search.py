DIMINUTIVE_TO_CANON: dict[str, tuple[str, ...]] = {
    k.replace("ё", "е"): tuple(c.replace("ё", "е") for c in v) for k, v in _RAW_DIMINUTIVES.items()
}

# Обратный индекс: канон → все уменьшительные
_CANON_TO_FORMS: dict[str, set[str]] = {}
for _dim, _canons in DIMINUTIVE_TO_CANON.items():
    for _c in _canons:
        _CANON_TO_FORMS.setdefault(_c, set()).add(_dim)
        _CANON_TO_FORMS[_c].add(_c)

