DIMINUTIVE_TO_CANON: dict[str, tuple[str, ...]] = {
    k.replace("ё", "е"): tuple(c.replace("ё", "е") for c in v) for k, v in _RAW_DIMINUTIVES.items()
}

# Обратный индекс: канон → все уменьшительные
_CANON_TO_FORMS: dict[str, set[str]] = {}
for _dim, _canons in DIMINUTIVE_TO_CANON.items():
    for _c in _canons:
        _CANON_TO_FORMS.setdefault(_c, set()).add(_dim)
        _CANON_TO_FORMS[_c].add(_c)

_NAME_CASE_SUFFIXES = (
    "ой", "ей", "ию", "ии", "ие", "ия", "ью", "ье", "ья",
    "ом", "ем", "ам", "ям", "ах", "ях",
    "у", "ю", "е", "ы", "и", "а", "я", "о",
)

_NAME_LOOKUP_RE = re.compile(
    r"(?:найд[иу]|найти|покажи|поищи|кто\s+так(?:ая|ой|ие)|есть\s+ли)\s+"
    r"([а-яёa-z]{2,}(?:\s+[а-яёa-z]{2,})?)",
    re.I,
)


def stem_name(token: str) -> str:
    """Укорачивает падежные окончания имени: ксюшу → ксюш."""
    c = token.lower().strip().replace("ё", "е")
    if len(c) < 3:
        return c
    for suf in _NAME_CASE_SUFFIXES:
        if len(c) > len(suf) + 2 and c.endswith(suf):
            return c[: -len(suf)]
    return c


def expand_name_variants(raw: str) -> list[str]:
    """Набор вариантов для ILIKE-поиска: оригинал, стем, каноны, уменьшительные."""
    raw_l = raw.lower().strip().replace("ё", "е")
    if not raw_l:
        return []
    stemmed = stem_name(raw_l)
    variants: set[str] = {raw_l, stemmed}

    lookup_keys = {raw_l, stemmed}
    # ксюш → попробовать ксюша / ксюшу как ключи словаря
    for suffix in ("а", "я", "у", "ю", ""):
        lookup_keys.add(stemmed + suffix)

    for key in lookup_keys:
        key_n = key.replace("ё", "е")
        if key_n in DIMINUTIVE_TO_CANON:
            for canon in DIMINUTIVE_TO_CANON[key_n]:
                variants.add(canon.replace("ё", "е"))
                for form in _CANON_TO_FORMS.get(canon, {canon}):
                    variants.add(form.replace("ё", "е"))

    cleaned = sorted({v for v in variants if len(v) >= 3})
    return cleaned


def extract_names_from_query(query: str) -> list[str]:
    """Эвристика: имя после «найди/покажи/кто такая» или одиночный токен-имя."""
    q = query.strip()
    if not q:
        return []
    m = _NAME_LOOKUP_RE.search(q)
    if m:
        token = m.group(1).strip()
        # отрезать хвост «в Москве» и т.п.
        token = re.split(r"\s+(?:в|во|из|из\s+города)\s+", token, maxsplit=1, flags=re.I)[0]
        parts = [p for p in re.findall(r"[а-яёa-z]{2,}", token.lower(), re.I) if len(p) >= 2]
        if parts:
            # Берём первое слово как имя (Ксюшу / Ксению Иванову → Ксюшу)
            return [parts[0]]

    # Запрос из одного-двух слов без явных «интересных» маркеров
    words = re.findall(r"[а-яёa-z]{3,}", q.lower(), re.I)
    interest_markers = ("любит", "йог", "спорт", "музык", "кино", "игр", "тусов", "встреч")
    if words and not any(any(m in w for m in interest_markers) for w in words):
        # «Ксюша», «Ксюшу пожалуйста»
        stop = {"пожалуйста", "можешь", "найти", "найди", "покажи", "есть"}
        candidates = [w for w in words if w not in stop]
        if len(candidates) == 1:
            return candidates
    return []
